/**
 * ServiceCategoryIcon maps service names to polished, gradient-backed glyphs.
 */
export function ServiceCategoryBadge({ serviceName = '', size = 'md' }) {
  const norm = (serviceName || '').toLowerCase()
  let icon = '🛠️'
  let bgClass = 'svc-bg-blue'
  let label = 'General'

  if (norm.includes('ac') || norm.includes('air')) {
    icon = '❄️'
    bgClass = 'svc-bg-cyan'
    label = 'HVAC'
  } else if (norm.includes('electr')) {
    icon = '⚡'
    bgClass = 'svc-bg-amber'
    label = 'Electrical'
  } else if (norm.includes('plumb')) {
    icon = '🔧'
    bgClass = 'svc-bg-sky'
    label = 'Plumbing'
  } else if (norm.includes('clean')) {
    icon = '✨'
    bgClass = 'svc-bg-emerald'
    label = 'Cleaning'
  } else if (norm.includes('carpent')) {
    icon = '🪚'
    bgClass = 'svc-bg-orange'
    label = 'Carpentry'
  } else if (norm.includes('paint')) {
    icon = '🎨'
    bgClass = 'svc-bg-purple'
    label = 'Painting'
  } else if (norm.includes('pest')) {
    icon = '🛡️'
    bgClass = 'svc-bg-green'
    label = 'Pest Control'
  } else if (norm.includes('appliance')) {
    icon = '⚙️'
    bgClass = 'svc-bg-rose'
    label = 'Appliances'
  }

  return (
    <div className={`svc-icon-box ${bgClass} svc-size-${size}`} title={label}>
      <span className="svc-emoji">{icon}</span>
    </div>
  )
}
